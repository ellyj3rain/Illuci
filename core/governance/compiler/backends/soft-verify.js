// illuci/core/governance/compiler/backends/soft-verify.js
//
// BACKEND: emit a soft-tier verification invariant. Post-hoc, never blocks; it reports a
// finding the runtime collects (the soft-verify pass). Same predicate evaluator as the hard
// tiers, but the verdict is advisory. Pure: returns {path, content}.

export function emitSoftVerify(ob, girHash) {
  const path = `core/governance/compiled/soft/${ob.id}.js`;
  const content = `// AUTO-GENERATED by the governance-compiler - do not edit by hand.
// Source obligation: ${ob.id}
// GIR: ${girHash}
import { evaluatePredicate } from "../../compiler/runtime/predicate.js";

export const OBLIGATION_ID = ${JSON.stringify(ob.id)};
export const TIER = "soft";
export const TRIGGER = ${JSON.stringify(ob.trigger)};
export const PREDICATE = ${JSON.stringify(ob.predicate || "")};

export function verify(context) {
  context = context || {};
  var r = evaluatePredicate(PREDICATE, context);
  return { ok: r.ok, code: r.ok ? "verified" : "soft-violation", obligation: OBLIGATION_ID, reason: r.reason };
}

export default { verify, OBLIGATION_ID, TIER, TRIGGER, PREDICATE };
`;
  return { path, content };
}

export default { emitSoftVerify };
