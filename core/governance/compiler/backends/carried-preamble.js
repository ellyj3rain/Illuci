// illuci/core/governance/compiler/backends/carried-preamble.js
//
// BACKEND: emit a carried-preamble constraint. A carried obligation does not block; it rides
// the agent's operating context as a stated constraint (the obligation text). The carry system
// loads these and folds PREAMBLE into the seat's context at TRIGGER time. Pure: {path, content}.

export function emitCarriedPreamble(ob, girHash) {
  const path = `core/governance/compiled/carried/${ob.id}.js`;
  const content = `// AUTO-GENERATED by the governance-compiler - do not edit by hand.
// Source obligation: ${ob.id}
// GIR: ${girHash}
export const OBLIGATION_ID = ${JSON.stringify(ob.id)};
export const TIER = "carried";
export const TRIGGER = ${JSON.stringify(ob.trigger)};
// The constraint carried into agent operating context.
export const PREAMBLE = ${JSON.stringify(ob.text || "")};

export default { OBLIGATION_ID, TIER, TRIGGER, PREAMBLE };
`;
  return { path, content };
}

export default { emitCarriedPreamble };
