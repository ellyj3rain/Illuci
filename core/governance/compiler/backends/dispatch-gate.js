// illuci/core/governance/compiler/backends/dispatch-gate.js
//
// BACKEND: emit a hard-tier dispatch-gate clause (pre-dispatch / session-init). Same blocking
// interface as a floor atom (check(context) -> {ok, code, reason}, armed), but scoped to the
// dispatch boundary rather than a file edit. Pure: returns {path, content}.

export function emitDispatchGate(ob, girHash) {
  const path = `core/governance/compiled/gate/${ob.id}.js`;
  const content = `// AUTO-GENERATED by the governance-compiler - do not edit by hand.
// Source obligation: ${ob.id}
// GIR: ${girHash}
import { arm } from "../../compiler/armed.js";
import { evaluatePredicate } from "../../compiler/runtime/predicate.js";

export const OBLIGATION_ID = ${JSON.stringify(ob.id)};
export const TIER = "hard";
export const TRIGGER = ${JSON.stringify(ob.trigger)};
export const PREDICATE = ${JSON.stringify(ob.predicate || "")};

export function check(context) {
  context = context || {};
  var r = evaluatePredicate(PREDICATE, context);
  var raw = r.ok
    ? { ok: true, code: "satisfied", reason: "[" + OBLIGATION_ID + "] " + r.reason }
    : { ok: false, code: "violation", reason: "[" + OBLIGATION_ID + "] " + r.reason };
  return arm(raw, { obligationId: OBLIGATION_ID, repoRoot: context.repoRoot, stamp: context.stamp });
}

export default { check, OBLIGATION_ID, TIER, TRIGGER, PREDICATE };
`;
  return { path, content };
}

export default { emitDispatchGate };
